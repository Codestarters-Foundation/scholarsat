/**
 * Builds src/data/vocab-bank.ts from scripts/vocab-src/*.txt.
 * Line format: word|part of speech|definition|example sentence|kind   (kind: c = classic hard word, x = everyday word used in an SAT sense)
 * Every definition and example is original text written for this project. Run: npx tsx scripts/build-vocab.ts
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const dir = path.join(process.cwd(), "scripts/vocab-src");
const base = readFileSync(path.join(process.cwd(), "src/data/vocab.ts"), "utf8");
const have = new Set([...base.matchAll(/^\s+V\("([^"]+)"/gm)].map((m) => m[1].toLowerCase()));
const baseCount = have.size;

const out: string[] = [];
const problems: string[] = [];
let dupes = 0;
for (const file of readdirSync(dir).filter((f) => f.endsWith(".txt")).sort()) {
  readFileSync(path.join(dir, file), "utf8").split("\n").forEach((line, i) => {
    if (!line.trim()) return;
    const where = `${file}:${i + 1}`;
    const parts = line.split("|");
    if (parts.length !== 5) return problems.push(`${where} expected 5 fields, got ${parts.length}: ${line.slice(0, 60)}`);
    const [word, pos, def, ex, kind] = parts.map((p) => p.trim());
    if (!/^[a-z][a-z -]*$/.test(word)) return problems.push(`${where} bad word "${word}"`);
    if (!["c", "x"].includes(kind)) return problems.push(`${where} bad kind for ${word}`);
    if (!/^(noun|verb|adj\.|adv\.)$/.test(pos)) problems.push(`${where} odd pos "${pos}" for ${word}`);
    if (def.length < 8 || ex.length < 20) problems.push(`${where} too short: ${word}`);
    if (def.toLowerCase().includes(word)) problems.push(`${where} definition uses the word itself: ${word}`);
    // the example must use the word (allowing endings like -ed, -ing, -s, -ly, -ion)
    const irregular: Record<string, string> = { cling: "clung", lend: "lent", strike: "struck", undertake: "undertook", uphold: "upheld" };
    const stem = irregular[word] ?? (word.length > 5 ? word.slice(0, word.length - 2) : word);
    if (!ex.toLowerCase().includes(stem.replace(/e$/, ""))) problems.push(`${where} example doesn't use "${word}": ${ex}`);
    if (have.has(word)) return void dupes++;
    have.add(word);
    out.push(`  V(${JSON.stringify(word)}, ${JSON.stringify(pos)}, ${JSON.stringify(def)}, ${JSON.stringify(ex)}, ${JSON.stringify(kind === "x" ? "context" : "classic")}),`);
  });
}

const header = `/** GENERATED by scripts/build-vocab.ts from scripts/vocab-src/*.txt. Do not edit by hand. */
import type { Vocab } from "./vocab";
const V = (word: string, pos: string, def: string, ex: string, kind: Vocab["kind"]): Vocab => ({ word, pos, def, ex, kind });

export const BANK: Vocab[] = [
`;
writeFileSync(path.join(process.cwd(), "src/data/vocab-bank.ts"), header + out.join("\n") + "\n];\n");
console.log(`base ${baseCount} + new ${out.length} (skipped ${dupes} duplicates) = ${baseCount + out.length}`);
if (problems.length) {
  console.log(`\n${problems.length} problems:`);
  problems.forEach((p) => console.log(" ", p));
  process.exitCode = 1;
}
